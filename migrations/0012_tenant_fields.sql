-- ------------------------------------------------------------
-- 1. ストレスチェックの有効化（段階2・3の中核）
--
-- 🔴 既定は 0（無効）。要配慮個人情報（個人情報保護法）を扱う機能を、
--    明示的な有効化なしに使える状態にはしない。
--    現行の時点で既にテナント単位のオプション機能であり、
--    段階3の SaaS 課金はこのフラグを土台にする。
-- ------------------------------------------------------------
ALTER TABLE tenants ADD COLUMN stress_check_enabled INTEGER NOT NULL DEFAULT 0;

-- ------------------------------------------------------------
-- 2. 連絡先
--    contact_name … 担当者名（現行 su1_rem2 と推定）
--    manager_name … 責任者名（現行 company_name2 と推定）
--    ⚠ どちらの推定も未確認だが、現行データを引き継がないため影響しない。
-- ------------------------------------------------------------
ALTER TABLE tenants ADD COLUMN contact_name TEXT;
ALTER TABLE tenants ADD COLUMN manager_name TEXT;

-- ------------------------------------------------------------
-- 3. 最大登録アカウント数
--
-- ⚠ 段階1は plans.max_employees（プラン単位）で設計したが、現行の発行画面は
--   テナントごとの直接指定だった（機能権限表 §1.2①）。
--   plans.max_employees は残し、テナント側の値を優先する。
--   NULL = テナント個別の指定なし＝プランに従う。
-- ------------------------------------------------------------
ALTER TABLE tenants ADD COLUMN max_accounts INTEGER;

-- ------------------------------------------------------------
-- 4. 年間始月（会社ごとの年度の区切り。1〜12）
--
-- 締日が「日」単位の区切り、年間始月が「月」単位の区切りという二段構え
-- （機能権限表 §1.2③【会話合意 2026-08-16】）。
-- ⚠ 実際に集計へ効かせるのは別チケット。0012 は列の追加まで。
-- ------------------------------------------------------------
ALTER TABLE tenants ADD COLUMN fiscal_start_month INTEGER;

-- ------------------------------------------------------------
-- 5. 値域の検査
