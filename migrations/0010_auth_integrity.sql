-- 目的: 「ログイン画面を1本にする」設計を、アプリ層だけでなく DB でも保証する
--
-- 経緯（Session 06 で検出）:
--   F-10 アプリ層は SELECT id FROM accounts WHERE login_id = ?1 で【全社】の一意を
--        検査しているが（services.ts registerEmployee / bootstrapSetup）、
--        DB 制約は UNIQUE (tenant_id, login_id) で【会社内】の一意しか保証していない。
--        単一ログイン画面は「IDだけで会社を特定できる」ことに依存しているため、
--        ここが破れると login() が tenant_required に落ち、会社選択欄が突然現れる。
--   F-11 roles の初期データがマイグレーションに存在せず、テストの中にしか無かった。
--        bootstrapSetup は accounts を INSERT した【後】に tenant_admin を探し、
--        無ければ invalid_input で中断する。アカウントだけが残る中途半端な状態になる。
--        新しい環境を再現できない状態でもあった。
--
-- ⚠ 適用時に「UNIQUE constraint failed」が出た場合は、会社をまたいで
--   login_id が重複している行が実在する。先に該当行を特定して改名すること。

-- ------------------------------------------------------------
-- F-10: ログインIDは会社をまたいで一意
-- ------------------------------------------------------------
CREATE UNIQUE INDEX IF NOT EXISTS ux_accounts_login_id ON accounts(login_id);

